"""宛先・目的レイヤ。『誰の資料を・誰に見せる・何のための』かでワーディングを決める。
事実(数値・固有名)は元ネタから接地したまま、言葉づかい(見出し・本文の声・敬体/専門度)だけを宛先で変える。

- propose(source): 元ネタから宛先を推定(claude・課金ゼロ)。人間が確認・修正する前提。
- describe(a): プロンプト用の宛先説明。
- organize.build_deck がこれを言葉づかいの指針として使う。
"""
from __future__ import annotations
import llm

# 選択肢(UI候補。free-text も可)
AUTHORS = ["売り手(サービス提供側)", "社内の担当者", "コンサル/支援者", "自社の事業", "研修・教育の講師"]
READERS = ["見込み客の決裁者", "顧客の現場担当", "投資家", "社内の役員・上長", "一般のお客様", "社内メンバー", "受講者・初心者"]
PURPOSES = ["受注・成約", "社内の合意形成", "状況の報告", "教育・啓蒙", "資金調達"]
TONES = ["敬体・フォーマル(丁寧)", "敬体・標準", "常体・簡潔", "やわらかい親しみ"]

DEFAULT = {"author": "売り手(サービス提供側)", "reader": "見込み客の決裁者",
           "purpose": "受注・成約", "tone": "敬体・フォーマル(丁寧)"}

SYSTEM = ("あなたは資料の編集ディレクターです。元ネタから、この資料が『誰の資料を・誰に見せる・"
          "何のための』ものかを推定し、相手に最も伝わるトーンを選びます。出力はJSONのみ。")


def propose(source_text: str) -> dict:
    prompt = f"""# 宛先・目的の推定
次の元ネタから、この資料の宛先と目的を推定してください。相手に伝わる言葉づかいの土台になります。
## 候補(近いものを選ぶ。無ければ自然な言葉で書いてよい)
- 誰の資料か(author): {" / ".join(AUTHORS)}
- 誰に見せるか(reader): {" / ".join(READERS)}
- 目的(purpose): {" / ".join(PURPOSES)}
- トーン(tone): {" / ".join(TONES)}
## 出力(JSONのみ)
{{"author":"...","reader":"...","purpose":"...","tone":"...","reason":"元ネタの根拠に触れた1文"}}
## 元ネタ
{source_text[:8000]}
"""
    try:
        r = llm.generate_json(prompt, SYSTEM)
    except Exception:
        r = {}
    a = dict(DEFAULT)
    for k in ("author", "reader", "purpose", "tone"):
        if isinstance(r, dict) and str(r.get(k, "")).strip():
            a[k] = str(r[k]).strip()
    a["reason"] = str((r or {}).get("reason", "元ネタの内容から推定しました。")).strip()
    return a


def describe(a: dict) -> str:
    a = a or DEFAULT
    return (f"- 誰の資料か: {a.get('author','')}\n"
            f"- 誰に見せるか: {a.get('reader','')}\n"
            f"- 目的: {a.get('purpose','')}\n"
            f"- トーン: {a.get('tone','')}")


def wording_rules(a: dict) -> str:
    a = a or DEFAULT
    reader = a.get("reader", "相手"); tone = a.get("tone", "")
    tone_line = ("- トーン「{t}」を全文で厳守する。".format(t=tone)
                 + ("敬体指定なら全ての文を『です・ます』で統一し、常体(だ・である調)を混ぜない。"
                    if "敬体" in tone else
                    "常体指定なら簡潔な常体でそろえる。" if "常体" in tone else
                    "指定のトーンに文末をそろえる。"))
    return (f"言葉づかいの原則(宛先={reader}):\n"
            f"- 見出し・本文は「{reader}が読む」前提で、相手に伝わる言葉にする。\n"
            f"{tone_line}\n"
            f"- 売り手/社内の内輪語や砕けた言い回し(例:「刺さる」「ガチ」「バズる」「ローンチ」)や、不要な専門用語・カタカナ語を使わない。相手が普通に使う言葉で言い換える。\n"
            f"- 出典由来の統計単位・会計科目・専門略語は、宛先が普段使う言い方に開く(例:12,000千人→約1,200万人、300,000百万円→約3,000億円、専門的な会計科目→普段使う費目名)。ただし数値そのものは変えない。\n"
            f"- 数字(特に金額)には必ず単位を付ける(裸の数字を置かない)。外貨(ドル等)は日本の宛先には円換算を併記する(例:100ドル(約1.5万円))。「〜から/税別」等の条件も落とさない。\n"
            f"- 相手の立場に語彙を合わせる(投資家には獲得規模/回収、決裁者には導入判断の語。市場賛美や消費者向けの砕けた擬態語にしない)。\n"
            f"- 締めは分けて: CTA(次の行動)は元ネタに具体があるときだけ。**示唆・結論(既出の事実を統合した解釈=何が言えるか/何を優先/どれを推すか)は必ず入れる**(新事実の追加でなく解釈なので捏造でない)。事実の再掲・『それぞれ特徴があります』『注視します』のような中身の無い締めは禁止。\n"
            f"- 相手への敬意を保つ。誇張・煽りをしない。事実(数値・固有名・比較の中身)は元ネタのままで、盛らない・作らない・変えない。")
